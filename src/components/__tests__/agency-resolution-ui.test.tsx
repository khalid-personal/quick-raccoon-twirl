// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { MemoryRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest';
import AgencyResolutionCenter from '../AgencyResolutionCenter';
import { getCandidates, saveCandidates, saveLocalAgencies, savePayments } from '@/lib/data-store';
import { saveBankStatement } from '@/lib/bank-statement-store';
import { getAgencyResolutionCases } from '@/lib/agency-resolution';
import { generateDemoDataset } from '@/lib/demo-dataset';
import { PageMemoryProvider } from '@/hooks/use-page-memory';
const auth = vi.hoisted(() => ({ user: { id: 'admin', email: 'admin@example.test' }, userRole: 'superadmin', userLocalAgencyId: null as string | null, userForeignAgencyId: null as string | null, isDemo: true, viewAs: null }));
vi.mock('@/lib/auth-context', () => ({ useAuth: () => auth }));
let container: HTMLDivElement, root: Root, client: QueryClient;
const click = async (label: string) => act(async () => {
  [...document.querySelectorAll<HTMLButtonElement>('button')].find(button => button.textContent?.trim() === label)!.click();
  await new Promise(resolve => setTimeout(resolve, 150));
});
const input = async (id: string, value: string) => act(async () => {
  const field = document.querySelector(`[data-field="${id}"]`)!;
  const prototype = field instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype;
  Object.getOwnPropertyDescriptor(prototype, 'value')!.set!.call(field, value);
  field.dispatchEvent(new Event('input', { bubbles: true }));
});
const render = async () => {
  await act(async () => root.render(<MemoryRouter><QueryClientProvider client={client}><AgencyResolutionCenter /></QueryClientProvider></MemoryRouter>));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 30)); });
};
beforeEach(() => {
  Object.defineProperty(globalThis, 'IS_REACT_ACT_ENVIRONMENT', { value: true, configurable: true });
  vi.spyOn(window, 'scrollTo').mockImplementation(() => {});
  localStorage.clear(); sessionStorage.clear(); sessionStorage.setItem('dawm_demo_session', '1');
  auth.userRole = 'superadmin'; auth.userLocalAgencyId = null; auth.user.id = 'admin';
  const candidate = { ...generateDemoDataset(Date.parse('2026-11-07')).candidates[0], local_agency_id: 'local' };
  saveCandidates([candidate]); saveLocalAgencies([{ id: 'local', name: 'Agency under review', created_at: '2026-11-07' }]);
  savePayments([{ id: 'p', amount: 100, currency: 'ETB', status: 'succeeded', payer_type: 'candidate', payer_foreign_agency_id: '', payee_local_agency_id: 'local', candidate_ids: [candidate.id], provider_reference: 'REF', created_at: '2026-11-07', updated_at: '2026-11-07' }]);
  saveBankStatement('local', { name: 'Bank statement', lines: [{ amount: 80, currency: 'ETB', reference: 'REF', description: 'Credit', date: '2026-11-07' }] }, 'candidate');
  client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  container = document.createElement('div'); document.body.append(container); root = createRoot(container);
});
afterEach(async () => { await act(async () => root.unmount()); client.clear(); container.remove(); vi.restoreAllMocks(); });
describe('guided agency resolution UI', () => {
  it('retains an inline review draft without retaining an automatic pause confirmation', async () => {
    const candidate = getCandidates()[0];
    saveBankStatement('local', { name: 'Bank credit.csv', lines: [{ amount: 80, currency: 'ETB', reference: 'REF', description: candidate.tracking_code, date: '2026-11-07' }] }, 'candidate');
    const retained = async (show: boolean) => {
      await act(async () => root.render(<MemoryRouter><QueryClientProvider client={client}><PageMemoryProvider>{show ? <AgencyResolutionCenter /> : <div>Another section</div>}</PageMemoryProvider></QueryClientProvider></MemoryRouter>));
      await act(async () => { await new Promise(resolve => setTimeout(resolve, 30)); });
    };
    await retained(true);
    await click('Review difference');
    await input('resolution-reason', 'Keep this review note while looking at another section');
    await act(async () => document.querySelector<HTMLInputElement>('[aria-label="Difference review workspace"] input[type="checkbox"]')!.click());
    await retained(false);
    await retained(true);
    expect(document.querySelector('[aria-label="Difference review workspace"]')).not.toBeNull();
    expect(document.querySelector<HTMLTextAreaElement>('[data-field="resolution-reason"]')?.value).toContain('Keep this review note');
    expect(document.querySelector<HTMLInputElement>('[aria-label="Difference review workspace"] input[type="checkbox"]')?.checked).toBe(false);
  });
  it('shows a candidate-linked comparison inline and automatically moves a confirmed shortfall to Agency paused', async () => {
    const candidate = getCandidates()[0];
    saveBankStatement('local', { name: 'Bank credit.csv', lines: [{ amount: 80, currency: 'ETB', reference: 'REF', description: `Credit for ${candidate.tracking_code}`, date: '2026-11-07' }] }, 'candidate');
    await render();
    await click('Review difference');
    const workspace = document.querySelector('[aria-label="Difference review workspace"]')!;
    expect(document.querySelector('[role="dialog"]')).toBeNull();
    expect(workspace.textContent).toContain(`${candidate.first_name} ${candidate.last_name}`);
    expect(workspace.textContent).toContain('100 ETB');
    expect(workspace.textContent).toContain('80 ETB');
    expect(workspace.querySelector('[aria-current="step"]')?.textContent).toContain('Check differences');
    await input('resolution-reason', 'Verified candidate, bank credit and exact transfer reference');
    await input('resolution-due', '2026-11-08');
    await act(async () => workspace.querySelector<HTMLInputElement>('input[type="checkbox"]')!.click());
    await click('Confirm checks and apply automatic pause');
    expect(getAgencyResolutionCases()[0]).toMatchObject({ state: 'suspended', holdActive: true });
    expect(document.querySelector('[aria-label="Agency paused"]')?.querySelectorAll('article')).toHaveLength(1);
    expect(workspace.querySelector('[aria-current="step"]')?.textContent).toContain('Agency paused');
    expect(workspace.textContent).toContain('Candidate-linked shortfall verified; agency paused');
  });
  it('walks through explicit escalation, suspension and a scoped agency appeal', async () => {
    await render();
    const stage = (name: string) => document.querySelector(`[aria-label="${name}"]`);
    expect(stage('New differences')?.querySelectorAll('article')).toHaveLength(1);
    expect(stage('Waiting for a reply')?.querySelectorAll('article')).toHaveLength(0);
    await click('Review difference');
    expect(document.querySelector('[role="dialog"]')).toBeNull();
    expect(stage('Difference review workspace')?.textContent).toContain('Check differences');
    expect(stage('Difference review workspace')?.textContent).not.toContain('Pause new activity for this agency');
    expect(stage('Automatic pause checks')?.textContent).toContain('Automatic pause is blocked');
    await input('resolution-reason', 'Investigate bank credit amount shortage');
    await input('resolution-due', '2020-01-01');
    await click('Start documented follow-up');
    expect(getAgencyResolutionCases()[0]).toMatchObject({ state: 'escalated', holdActive: false });
    expect(stage('New differences')?.querySelectorAll('article')).toHaveLength(0);
    expect(stage('Waiting for a reply')?.querySelectorAll('article')).toHaveLength(1);
    expect(stage('Waiting for a reply')?.textContent).toContain('Reply overdue');
    await input('resolution-reason', 'Pause new registrations pending the deposit explanation');
    await click('Pause new activity for this agency');
    expect(getAgencyResolutionCases()[0].holdActive).toBe(true);
    expect(stage('Waiting for a reply')?.querySelectorAll('article')).toHaveLength(0);
    expect(stage('Agency paused')?.querySelectorAll('article')).toHaveLength(1);
    await act(async () => root.unmount());
    root = createRoot(container);
    auth.userRole = 'local-agency'; auth.userLocalAgencyId = 'local'; auth.user.id = 'local-user';
    await render();
    await click('Explain or appeal');
    expect(stage('Difference review workspace')?.textContent).not.toContain('Pause new activity for this agency');
    expect(stage('Automatic pause checks')).toBeNull();
    await input('resolution-reason', 'The bank deducted a fee and we have confirmation');
    await input('resolution-url', 'https://example.test/bank-confirmation.pdf');
    await click('Send explanation or appeal');
    expect(getAgencyResolutionCases()[0]).toMatchObject({ state: 'appealed', holdActive: true });
    expect(stage('Appeals to review')?.querySelectorAll('article')).toHaveLength(1);
    expect(stage('Appeals to review')?.textContent).not.toContain('Reply overdue');
    expect(stage('Agency paused')?.querySelectorAll('article')).toHaveLength(0);
    expect(stage('New differences')).toBeNull();
    await act(async () => root.unmount());
    root = createRoot(container);
    auth.userRole = 'superadmin'; auth.userLocalAgencyId = null; auth.user.id = 'admin';
    await render();
    await click('Review this issue');
    await input('resolution-reason', 'Bank explanation reviewed and agency activity approved');
    await click('Accept explanation and lift suspension');
    expect(getAgencyResolutionCases()[0]).toMatchObject({ state: 'resolved', holdActive: false });
    await click('Closed cases');
    expect(stage('Closed cases')?.querySelectorAll('article')).toHaveLength(1);
    expect(stage('Closed cases')?.textContent).toContain('Issue closed');
  });
});
